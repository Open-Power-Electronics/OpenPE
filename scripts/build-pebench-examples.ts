import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { exportKiCad, importDocument, parseProject, serializeProject } from '../lib/project';

const directory = 'tests/fixtures/pebench';
const index = JSON.parse(await readFile(`${directory}/upstream-index.json`, 'utf8')) as {
  id: string;
  title: string;
  description: string;
  pebenchId: string;
  repository: string;
  commit: string;
  license: string;
  notices: string[];
  sourceDirectory: string;
  schematic: { file: string; path: string; sha256: string };
  pcb: { file: string; path: string; sha256: string };
  convertedPCB: { file: string; sha256: string };
  acceptance: unknown;
  drc: unknown;
  qualification: string;
}[];
if (index.length !== 10 || new Set(index.map((entry) => entry.id)).size !== 10)
  throw new Error('PEBench regression fixtures require exactly ten independent pinned designs.');
const hash = (source: string | Uint8Array) => createHash('sha256').update(source).digest('hex');
const stableId = (seed: string) => {
  const hex = hash(seed);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
};
const manifest = {
  collection: 'PEBench',
  description:
    'Ten editable source-derived schematic and PCB examples. Retained educational references, not qualified zero-DRC benchmark samples.',
  examples: index.map((entry) => ({
    id: entry.id,
    title: entry.title,
    description: entry.description,
    pebenchId: entry.pebenchId,
    license: entry.license,
    source: {
      repository: entry.repository,
      commit: entry.commit,
      attribution: entry.repository.includes('/sparkfun/')
        ? 'SparkFun Electronics and original design contributors'
        : 'Adafruit Industries and original design contributors',
      schematic: {
        path: `${directory}/upstream/${entry.id}/${entry.schematic.file}`,
        upstreamPath: entry.schematic.path,
        sha256: entry.schematic.sha256,
      },
      pcb: {
        path: `${directory}/upstream/${entry.id}/${entry.pcb.file}`,
        upstreamPath: entry.pcb.path,
        sha256: entry.pcb.sha256,
      },
      convertedPCB: {
        path: `${directory}/upstream/${entry.id}/${entry.convertedPCB.file}`,
        sha256: entry.convertedPCB.sha256,
      },
      notices: entry.notices.map((file) => `${directory}/upstream/${entry.id}/${file}`),
    },
    qualification: entry.qualification,
  })),
};
await writeFile(`${directory}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n');
if (process.argv.includes('--catalog-only')) process.exit(0);
const { convertExamplePCB } = await import('./example-pcb');

const audit = [];
for (const entry of manifest.examples) {
  const meta = index.find((item) => item.id === entry.id)!;
  for (const source of [entry.source.schematic, entry.source.pcb, entry.source.convertedPCB]) {
    const bytes = await readFile(source.path);
    if (hash(bytes) !== source.sha256)
      throw new Error(`PEBench source checksum mismatch: ${source.path}`);
  }
  const source = await readFile(`${directory}/converted/${entry.id}.kicad_sch`, 'utf8');
  const schematicAudit = JSON.parse(
    await readFile(`${directory}/converted/${entry.id}.audit.json`, 'utf8'),
  );
  if (schematicAudit.sourceSha256 !== entry.source.schematic.sha256)
    throw new Error(`${entry.id}: stale schematic conversion; regenerate from the pinned source.`);
  const project = importDocument(source);
  project.id = stableId(`${entry.id}:project`);
  project.name = entry.title;
  project.schematic.title = entry.title;
  const conversion = convertExamplePCB(
    await readFile(entry.source.convertedPCB.path, 'utf8'),
    project.schematic,
    entry.id,
    JSON.parse(await readFile(`${directory}/upstream/${entry.id}/eagle_source_audit.json`, 'utf8'))
      .reference_mapping ?? {},
  );
  project.pcb = conversion.board;
  project.extensions['org.openpe.pebench-example'] = {
    id: entry.id,
    pebenchId: entry.pebenchId,
    source: entry.source,
    license: entry.license,
    qualification: entry.qualification,
    sourceAcceptance: meta.acceptance,
    sourceDRC: meta.drc,
    changes:
      'EAGLE schematic converted with original embedded symbol geometry, gates and physical pin mappings; PEBench KiCad PCB represented as editable structured geometry. Native source files and notices retained. Polygon curves in schematic artwork tessellated within 0.005 mm. PCB zone boundaries and settings retained; cached zone fill is regenerated by KiCad. No simulation profile is added.',
  };
  const canonical = serializeProject(project);
  const reopened = parseProject(canonical);
  await writeFile(`${directory}/${entry.id}.openpe.json`, canonical);
  await writeFile(`${directory}/${entry.id}.kicad_sch`, exportKiCad(reopened, 'schematic'));
  await writeFile(`${directory}/${entry.id}.kicad_pcb`, exportKiCad(reopened, 'pcb'));
  audit.push({
    id: entry.id,
    bytes: Buffer.byteLength(canonical),
    sha256: hash(canonical),
    schematic: {
      components: project.schematic.parts.length,
      wires: project.schematic.wires.length,
    },
    pcb: {
      footprints: project.pcb.footprints.length,
      pads: project.pcb.footprints.reduce((sum, f) => sum + f.pads.length, 0),
      tracks: project.pcb.tracks.length,
      vias: project.pcb.vias.length,
      layers: project.pcb.layers,
      zones: project.pcb.zones.length,
    },
    conversion: conversion.audit,
  });
  console.log(
    `${entry.id}: ${Buffer.byteLength(canonical)} bytes, schematic + ${project.pcb.layers.length}-layer Layout`,
  );
}
await writeFile(`${directory}/conversion-audit.json`, JSON.stringify(audit, null, 2) + '\n');

const licenseDirectory = 'tests/fixtures/pebench/licenses';
await mkdir(licenseDirectory, { recursive: true });
await copyFile('public/licenses/kicad-demos/LICENSE.txt', `${licenseDirectory}/CC-BY-SA-4.0.txt`);
const sa3 = index.find(
  (entry) =>
    entry.license === 'CC-BY-SA-3.0' && entry.notices.some((file) => /license\.txt$/i.test(file)),
)!;
if (!sa3) throw new Error('The pinned CC-BY-SA-3.0 legal text is missing.');
await copyFile(
  path.join(
    directory,
    'upstream',
    sa3.id,
    sa3.notices.find((file) => /license\.txt$/i.test(file))!,
  ),
  `${licenseDirectory}/CC-BY-SA-3.0.txt`,
);
const notices = [
  'PEBench source-derived schematic and PCB examples',
  '',
  "These hardware documents retain the original licenses. They are not licensed under OpenPE's software license.",
  'Original notices and license texts follow. OpenPE is independent of the original designers.',
  'Changes: EAGLE schematic conversion with embedded upstream symbol geometry and physical pin maps; editable OpenPE PCB conversion; regenerated KiCad 10 exports; fresh IDs for each opened copy. Curved schematic artwork polygons are tessellated within 0.005 mm. PCB cached zone fill must be regenerated in KiCad.',
  'These are educational design references with retained source verification status. No new ERC, DRC, production or simulation qualification is claimed.',
];
for (const entry of manifest.examples) {
  notices.push(
    '',
    `${entry.title} — ${entry.source.attribution}`,
    `${entry.source.repository}/tree/${entry.source.commit}`,
    `Schematic: ${entry.source.schematic.upstreamPath}`,
    `Board: ${entry.source.pcb.upstreamPath}`,
    `License: ${entry.license} — https://creativecommons.org/licenses/by-sa/${entry.license.endsWith('3.0') ? '3.0' : '4.0'}/`,
  );
  for (const file of entry.source.notices)
    notices.push('', `Original notice: ${path.basename(file)}`, await readFile(file, 'utf8'));
}
await writeFile(`${licenseDirectory}/NOTICE.txt`, notices.join('\n') + '\n');
console.log(
  'Generated ten pinned PEBench regression projects, fixture snapshots, native exports and license notices.',
);
